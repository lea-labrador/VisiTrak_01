// Helper function to get all municipalities
export const getMunicipalities = () => {
  return Object.keys(boholAddressData).sort();
};

// Helper function to get barangays for a municipality
export const getBarangays = (municipality) => {
  return boholAddressData[municipality] || [];
};

// Helper function to validate address
export const validateBoholAddress = (municipality, barangay) => {
  if (!municipality || !barangay) return false;
  const barangays = boholAddressData[municipality];
  return barangays && barangays.includes(barangay);
};

// Helper function to format address for database
export const formatAddressForDB = (municipality, barangay) => {
  if (!municipality || !barangay) return null;
  return {
    barangay,
    municipality,
    province: "Bohol",
    fullAddress: `${barangay}, ${municipality}, Bohol`,
    country: "Philippines"
  };
};